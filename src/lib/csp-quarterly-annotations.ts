import {annotationForCspKind} from './csp-annotation-rules.ts';
import {readCspRowAnnotations} from './csp-row-annotations.ts';
import {cspNameHeader} from './csp-table-header.ts';
import type {CspPage,CspTextItem} from './csp-extract.ts';
import type {QuarterlyEvent} from './csp-quarterly-report.ts';

const norm=(v:unknown)=>String(v||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'')
 .toUpperCase().replace(/[^A-Z0-9]+/g,' ').trim();

/** Enrich only the read-only report projection with notes reread from original
 * PDFs. Never alter event identity, approval, salary progression or CSP keys.
 */
export function enrichQuarterlyAnnotations(events:QuarterlyEvent[],read:QuarterlyEvent[]):QuarterlyEvent[]{
 return events.map(event=>{
  const same=(other:QuarterlyEvent)=>other.kind===event.kind&&norm(other.name)===norm(event.name);
  let match=read.find(other=>other.id===event.id&&same(other));
  if(!match){
   // Without an exact row id, never guess when this agent has multiple
   // same-kind same-date decisions (including cumulative advancements).
   const ownDuplicates=events.filter(other=>other.kind===event.kind&&
    norm(other.name)===norm(event.name)&&other.effective===event.effective);
   if(ownDuplicates.length===1){
    const possible=read.filter(other=>same(other)&&other.effective===event.effective&&
     (event.page===undefined||other.page===event.page||
       (Array.isArray(event.pages)&&other.page!==undefined&&event.pages.includes(other.page))));
    if(possible.length===1)match=possible[0];
   }
  }
  if(!match)return event;
  const movementReason=event.movementReason||match.movementReason;
  const observations=event.observations||match.observations;
  if(!movementReason&&!observations)return event;
  return {...event,...(movementReason?{movementReason}:{}),...(observations?{observations}:{})};
 });
}

/** Reread only printed annotation cells in an original ODJ, anchored by the
 * agent's name, rather than relying on the event IDs generated by a new
 * extraction. This is a fallback for old validated documents where PDF
 * column widths or row parsing have changed in the meantime.
 *
 * Does not infer any GF/NR, approve events, or change persisted CSP records.
 */
export function recoverQuarterlyAnnotationsFromPages(events:QuarterlyEvent[],pages:CspPage[]):QuarterlyEvent[]{
 const pagesByNumber=new Map(pages.map(p=>[p.page,p]));
 return events.map(event=>{
  const field=annotationForCspKind(event.kind);
  if(!field||event[field]||!event.page)return event;
  const page=pagesByNumber.get(event.page);
  if(!page)return event;
  const head=cspNameHeader(page.items)?.head;
  if(!head)return event;
  const title=page.items.find(i=>{
   const label=norm(i.str);
   return field==='movementReason'?/^MOTIFS?(?: |$)/.test(label):
    /^(?:OBSERVATIONS?|COMMENTAIRES?|REMARQUES?)(?: |$)/.test(label);
  });
  if(!title||Math.abs(title.y-head.y)>70)return event;
  const firstCenter=head.x+head.width/2;
  const rightHeader=page.items.filter(i=>i.x+i.width/2>firstCenter+35&&
    i.y>=head.y-32&&i.y<=head.y+45)
   .sort((a,b)=>a.x+a.width/2-b.x-b.width/2)[0];
  if(!rightHeader)return event;
  const cutoff=(firstCenter+rightHeader.x+rightHeader.width/2)/2;
  const rowItems=page.items.filter(i=>i.str.trim()&&
    i.y<head.y-7&&i.y>page.height*.06&&i.x+i.width/2<cutoff);
  const lines:{y:number;items:CspTextItem[];text:string}[]=[];
  for(const item of rowItems.sort((a,b)=>b.y-a.y||a.x-b.x)){
   let line=lines.find(r=>Math.abs(r.y-item.y)<3);
   if(!line){line={y:item.y,items:[],text:''};lines.push(line);}
   line.items.push(item);
  }
  for(const line of lines){
   line.items.sort((a,b)=>a.x-b.x);
   line.text=line.items.map(i=>i.str).join(' ');
  }
  const matching=lines.filter(line=>norm(line.text)===norm(event.name));
  if(matching.length!==1)return event;
  const y=matching[0].y;
  const neighbors=lines.filter(line=>line!==matching[0]&&
   /^[A-ZÀ-Ÿ][A-ZÀ-Ÿ '\-’]+$/iu.test(line.text.trim())&&
   line.text.trim().split(/\s+/).length>=2);
  const upper=[head.y-7,...neighbors.map(r=>(r.y+y)/2).filter(v=>v>y)];
  const lower=[page.height*.06,...neighbors.map(r=>(r.y+y)/2).filter(v=>v<y)];
  const top=Math.min(...upper),bottom=Math.max(...lower);
  const band=page.items.filter(i=>i.y<top&&i.y>bottom);
  const found=readCspRowAnnotations(page,head.y,band)[field];
  return found?{...event,[field]:found}:event;
 });
}
